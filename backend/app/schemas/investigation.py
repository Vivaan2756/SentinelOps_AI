"""Pydantic schemas for Agentic AI Incident Investigation."""

from datetime import datetime
from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field, ConfigDict


class EvidenceItem(BaseModel):
    """Diagnostic evidence item collected from approved telemetry sources."""
    evidence_id: str = Field(description="Unique identifier for evidence item, e.g. ev-1")
    source: str = Field(description="Telemetry source, e.g. health_probe, prometheus_metrics")
    observation: str = Field(description="Human-readable observed facts or raw output")
    timestamp: str = Field(description="ISO timestamp when observation was gathered")
    collection_status: str = Field(
        default="success", description="Status: success, failed, degraded, not_available"
    )
    data: Optional[Dict[str, Any]] = Field(
        default=None, description="Structured payload, status code, latency, or metrics data"
    )

    model_config = ConfigDict(from_attributes=True)


class Hypothesis(BaseModel):
    """Candidate root-cause hypothesis evaluated against collected evidence."""
    hypothesis_id: str = Field(description="Identifier for hypothesis, e.g. hyp-1")
    root_cause: str = Field(description="Succinct description of the candidate root cause")
    supporting_evidence_ids: List[str] = Field(
        default_factory=list, description="IDs of evidence items that support this hypothesis"
    )
    contradicting_evidence_ids: List[str] = Field(
        default_factory=list, description="IDs of evidence items that contradict this hypothesis"
    )
    explanation: str = Field(description="Detailed technical reasoning connecting evidence to root cause")
    confidence: float = Field(
        ge=0.0, le=1.0, description="Evidential support score between 0.0 and 1.0"
    )
    rank: Optional[int] = Field(
        default=None, description="Ordinal priority rank (1 = most supported)"
    )
    is_supported: bool = Field(
        default=True, description="Whether claims are verified against actual evidence"
    )
    evaluation_notes: Optional[str] = Field(
        default=None, description="Deterministic validator feedback or contradiction notes"
    )

    model_config = ConfigDict(from_attributes=True)


class HypothesisGenerationOutput(BaseModel):
    """Structured LLM output for hypothesis generation."""
    hypotheses: List[Hypothesis] = Field(
        description="List of candidate root-cause hypotheses strictly referencing evidence IDs"
    )
    evidence_sufficient: bool = Field(
        default=True, description="True if evidence is adequate for diagnosis; False if indeterminate"
    )
    reasoning_notes: Optional[str] = Field(
        default=None, description="Preliminary synthesis notes or unaddressed anomalies"
    )


class PlaybookCompatibilityResult(BaseModel):
    """Result of evaluating a single candidate playbook's compatibility with an incident."""
    playbook_id: str = Field(description="UUID of evaluated playbook")
    playbook_name: str = Field(description="Human-readable name of playbook")
    version_number: int = Field(description="Active specification version evaluated")
    action_template_id: str = Field(description="Allowlisted action template ID")
    is_compatible: bool = Field(description="Whether the playbook passed all compatibility criteria")
    rejection_reasons: List[str] = Field(
        default_factory=list, description="List of reasons if rejected by deterministic evaluation"
    )
    matching_scenarios: List[str] = Field(
        default_factory=list, description="Playbook trigger scenarios matching incident symptoms"
    )
    matching_evidence_ids: List[str] = Field(
        default_factory=list, description="Evidence IDs matching this candidate"
    )
    missing_parameters: List[str] = Field(
        default_factory=list, description="Required parameters that could not be resolved"
    )
    validated_parameters: Dict[str, Any] = Field(
        default_factory=dict, description="Validated parameters conforming to action schema"
    )
    risk_level: str = Field(default="medium", description="Risk level (low, medium, high)")
    priority: int = Field(default=0, description="Service association priority")
    compatibility_explanation: str = Field(
        default="", description="Explanation of compatibility determination"
    )

    model_config = ConfigDict(from_attributes=True)


class RemediationRecommendation(BaseModel):
    """Structured dynamic remediation recommendation generated by LangGraph investigation."""
    outcome: str = Field(
        description="Outcome: compatible_found, multiple_compatible, no_compatible_playbook, missing_parameters, escalation_required"
    )
    status: str = Field(
        description="Status: actionable, human_escalation_required, insufficient_parameters"
    )
    playbook_id: Optional[str] = Field(default=None, description="UUID of recommended playbook")
    playbook_name: Optional[str] = Field(default=None, description="Name of recommended playbook")
    playbook_version: Optional[int] = Field(default=None, description="Active version of recommended playbook")
    action_template_id: Optional[str] = Field(default=None, description="Allowlisted action template ID")
    service_id: Optional[str] = Field(default=None, description="Target service UUID")
    workspace_id: Optional[str] = Field(default=None, description="Tenant workspace UUID")
    incident_id: Optional[str] = Field(default=None, description="Target incident UUID")
    investigation_id: Optional[str] = Field(default=None, description="Parent investigation UUID")
    risk_level: Optional[str] = Field(default=None, description="Risk level (low, medium, high)")
    parameters: Dict[str, Any] = Field(
        default_factory=dict, description="Validated parameters ready for policy evaluation"
    )
    explanation: str = Field(
        default="", description="Detailed reasoning connecting diagnosed root cause to playbook recommendation"
    )
    supporting_evidence_ids: List[str] = Field(
        default_factory=list, description="Telemetry evidence IDs supporting this recommendation"
    )
    missing_parameters: List[str] = Field(
        default_factory=list, description="Parameters missing for complete execution"
    )
    compatible_playbooks: List[PlaybookCompatibilityResult] = Field(
        default_factory=list, description="All compatible candidate playbooks"
    )
    rejected_playbooks: List[PlaybookCompatibilityResult] = Field(
        default_factory=list, description="Rejected candidate playbooks with reasons"
    )
    ranked_candidates: List[PlaybookCompatibilityResult] = Field(
        default_factory=list, description="Ranked compatible candidates"
    )
    escalation_reason: Optional[str] = Field(
        default=None, description="Explanation why human escalation is required"
    )

    model_config = ConfigDict(from_attributes=True)


class InvestigationSummary(BaseModel):
    """Explainable investigation summary and SRE recommendations."""
    incident_summary: str = Field(description="Executive technical summary of the incident")
    likely_root_cause: str = Field(description="Top-ranked diagnosed root cause")
    ranked_hypotheses: List[Hypothesis] = Field(
        default_factory=list, description="All evaluated hypotheses in descending order of support"
    )
    supporting_evidence: List[str] = Field(
        default_factory=list, description="Key facts supporting the primary diagnosis"
    )
    contradicting_evidence: List[str] = Field(
        default_factory=list, description="Observations that conflict with or weaken alternative hypotheses"
    )
    confidence_and_limitations: str = Field(
        description="Explanation of confidence score and uncertainty boundaries"
    )
    unresolved_questions: List[str] = Field(
        default_factory=list, description="Questions that require deeper or internal inspection"
    )
    recommended_next_steps: List[str] = Field(
        default_factory=list,
        description="Informational next diagnostic actions for the SRE engineer (READ-ONLY)",
    )
    limitations: str = Field(
        description="Scope and boundary limitations of this diagnostic run"
    )
    remediation_recommendation: Optional[RemediationRecommendation] = Field(
        default=None,
        description="Structured dynamic playbook recommendation (Phase 4.3)",
    )

    model_config = ConfigDict(from_attributes=True)


class InvestigationResponse(BaseModel):
    """Complete API response model for an incident investigation."""
    id: str
    incident_id: str
    workspace_id: str
    status: str
    model_name: str
    prompt_version: str
    evidence: List[EvidenceItem] = Field(default_factory=list)
    hypotheses: List[Hypothesis] = Field(default_factory=list)
    summary: Optional[InvestigationSummary] = None
    remediation_recommendation: Optional[RemediationRecommendation] = None
    error_message: Optional[str] = None
    token_usage: Optional[Dict[str, Any]] = None
    started_at: Optional[datetime] = None
    completed_at: Optional[datetime] = None
    created_at: datetime
    updated_at: datetime

    model_config = ConfigDict(from_attributes=True)


class StartInvestigationRequest(BaseModel):
    """Request payload to initiate or re-run an investigation."""
    force_refresh: bool = Field(
        default=False, description="Whether to re-run investigation if a completed one exists"
    )
